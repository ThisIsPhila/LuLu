import { createHash } from 'node:crypto';

const CACHE_PREFIX = 'lulu-app-static-shell-v1-';
const PUBLIC_ASSETS = new Set([
  '/media/brand/lu-mark-black.png',
  '/media/brand/lu-mark-white.png',
  '/media/brand/lulu-wordmark-black.png',
  '/media/brand/lulu-wordmark-white.png',
]);

function isAllowedAsset(url) {
  if (url === '/index.html' || PUBLIC_ASSETS.has(url)) return true;
  return /^\/assets\/[a-zA-Z0-9._/-]+$/.test(url) && !url.split('/').includes('..') && !url.endsWith('.map');
}

export function createOfflineWorkerSource(inputAssets) {
  const unique = new Map();
  for (const asset of inputAssets) {
    if (!asset || typeof asset.url !== 'string' || !isAllowedAsset(asset.url)) {
      throw new TypeError(`Offline shell asset is outside the app allowlist: ${asset?.url ?? 'unknown'}`);
    }
    if (unique.has(asset.url)) throw new TypeError(`Offline shell asset is duplicated: ${asset.url}`);
    unique.set(asset.url, asset.content);
  }
  if (!unique.has('/index.html')) throw new TypeError('The app index must be included in the offline shell.');

  const urls = [...unique.keys()].sort();
  const fingerprintInput = urls.map(url => {
    const value = unique.get(url);
    const bytes = typeof value === 'string' ? Buffer.from(value) : Buffer.from(value);
    return `${url}:${createHash('sha256').update(bytes).digest('hex')}`;
  }).join('\n');
  const version = createHash('sha256').update(fingerprintInput).digest('hex').slice(0, 16);

  return `/* Generated by Vite for the production app shell. */
const CACHE_PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const CACHE_NAME = CACHE_PREFIX + ${JSON.stringify(version)};
const PRECACHE_URLS = ${JSON.stringify(urls)};
const INDEX_PATH = '/index.html';

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const existingNames = await caches.keys();
    const cacheAlreadyExisted = existingNames.includes(CACHE_NAME);
    try {
      const cache = await caches.open(CACHE_NAME);
      await cache.addAll(PRECACHE_URLS);
    } catch (error) {
      if (!cacheAlreadyExisted) await caches.delete(CACHE_NAME);
      throw error;
    }
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(names => Promise.all(
    names.filter(name => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME).map(name => caches.delete(name))
  )));
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    if (url.pathname !== '/' && url.pathname !== INDEX_PATH) return;
    event.respondWith((async () => {
      try {
        return await fetch(request);
      } catch {
        const cache = await caches.open(CACHE_NAME);
        return await cache.match(INDEX_PATH) || Response.error();
      }
    })());
    return;
  }

  if (!PRECACHE_URLS.includes(url.pathname) || url.search) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(url.pathname);
    return cached || fetch(request);
  })());
});
`;
}
